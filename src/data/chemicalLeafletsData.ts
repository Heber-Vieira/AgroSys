// Deduplicate raw database and export the clean version
export const CHEMICAL_LEAFLETS_DATABASE: ChemicalLeaflet[] = (() => {
  const seen = new Set<string>();
  const unique: ChemicalLeaflet[] = [];
  for (const item of RAW_CHEMICAL_LEAFLETS_DATABASE) {
    if (!seen.has(item.id)) {
      seen.add(item.id);
      unique.push(item);
    }
  }
  return unique;
})();

function removeAccents(str: string): string {
  if (!str) return '';
  return str.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

// Helper search function
export function searchChemicalLeaflets(
  query: string, 
  categoryFilter: string = 'ALL',
  cropFilter: string = 'ALL'
): ChemicalLeaflet[] {
  const cleanQ = removeAccents(query.trim());

  return CHEMICAL_LEAFLETS_DATABASE.filter(item => {
    // Category match
    if (categoryFilter !== 'ALL') {
      if (categoryFilter === 'INSECTICIDE') {
        // Group Insecticide, Acaricide, Nematicide under "Inseticidas & Acaricidas"
        if (item.category !== 'INSECTICIDE' && item.category !== 'ACARICIDE' && item.category !== 'NEMATICIDE') {
          return false;
        }
      } else if (item.category !== categoryFilter) {
        return false;
      }
    }

    // Crop match
    if (cropFilter !== 'ALL') {
      const cleanCropFilter = removeAccents(cropFilter);
      const matchesCrop = item.targetCrops.some(c => {
        const cleanC = removeAccents(c);
        return cleanC.includes(cleanCropFilter) || cleanCropFilter.includes(cleanC);
      });
      if (!matchesCrop) return false;
    }

    // Text search
    if (!cleanQ) return true;

    const matchesName = removeAccents(item.commercialName).includes(cleanQ);
    const matchesAI = removeAccents(item.activeIngredient).includes(cleanQ);
    const matchesGroup = removeAccents(item.chemicalGroup).includes(cleanQ);
    const matchesMfg = removeAccents(item.manufacturer).includes(cleanQ);
    const matchesMapa = removeAccents(item.mapaRegistration).includes(cleanQ);
    const matchesTargets = item.targets.some(t => 
      removeAccents(t.pestName).includes(cleanQ) || 
      removeAccents(t.scientificName).includes(cleanQ)
    );

    return matchesName || matchesAI || matchesGroup || matchesMfg || matchesMapa || matchesTargets;
  });
}
